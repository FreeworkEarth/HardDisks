#!/usr/bin/env python3
"""##CHRIS 2026-10-15 (plan-author decision 57, addendum 1, task 1; notes 261012 sec. 4.7.137): THE VACANCY TABLE FOR THE STAGE 2
REGISTRATION (no runs). For the 14 Stage 2 cells (N 900 and 1600; eta 0.69, 0.70, 0.72, 0.74, 0.76, 0.78, 0.80) and both pins
(--gen3-lattice-orientation 0 and turned), every box height on the binary's grid, H = k/24 sigma, within 25-36 sigma (N 900: k 600..864)
and 34-48 sigma (N 1600: k 816..1152), N and eta kept and L0 = N pi / (8 H eta) following (decision 57's G2 rule): the arrangement the
binary's lattice fit chooses at that height (p2_lattice.lattice_fit, the replica of g3_lattice_fit checked against the binary in 42 of
42 starts, Report D56-1 (b); both compartments alike), its vacancies per compartment, its start strain e and its smallest gap.
THE TABLE lists every arrangement the fit chooses with at most 1 vacancy per compartment: the heights at which it is chosen (runs of
consecutive k), e over those heights, and at the height with the smallest |e| (then the k nearest the stage 1 height 10 sqrt(N/100):
k 720 for N 900, 960 for N 1600): H, L0, the aspect W/H (W = L0 - t/2, the compartment's width, t = 0.05 sigma the divider), e and the
gap. A cell and pin without such a height says so, with the fewest vacancies the range offers. Every height is checked through the C
library's strtof and the float product, as the binary reads --height (gen_p2_koa_261016.height_px); the text is "30"-style for whole
numbers, else 17 significant digits, as in the P2 task list. Two notes follow the table: the arrangement at the stage 1 heights, and
the heights at which both pins have at most 1 vacancy (one box for both pins). A check: the fit again with L0 rounded to float32,
in case the binary holds L0 in single precision; the number of heights whose arrangement changes is printed.
usage (from hspist3/): python3 cluster/gen3_stage2_261016/s2_vacancy_table.py [--out <folder>]
writes s2_vacancy_table_261015.md (the table) and s2_vacancy_table_261015_heights.csv (the table's long form: every height of the
range, with its arrangement, vacancies, e and gap) into the folder of this script, or into --out.
"""
import csv, math, os, sys
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import p2_lattice as LT
from gen_p2_koa_261016 import height_px

ETAS = (0.69, 0.70, 0.72, 0.74, 0.76, 0.78, 0.80); PINS = ("0", "turned")
KR = {900: range(600, 865), 1600: range(816, 1153)}; KREF = {900: 720, 1600: 960}
OUTD = os.path.abspath(sys.argv[sys.argv.index("--out") + 1]) if "--out" in sys.argv else HERE
MD = os.path.join(OUTD, "s2_vacancy_table_261015.md"); CSV = os.path.join(OUTD, "s2_vacancy_table_261015_heights.csv")


def htext(k): return f"{k // 24}" if k % 24 == 0 else f"{k / 24.0:.17g}"


def fit(N, eta, k, pin):
    H = k / 24.0; L0 = N * math.pi / (8.0 * H * eta)
    b = LT.lattice_fit(N // 2, 0.5 * LT.PX, L0 * LT.PX - 0.5 * LT.TH * LT.PX, float(k), 0 if pin == "0" else 1)
    b32 = LT.lattice_fit(N // 2, 0.5 * LT.PX, float(np.float32(L0)) * LT.PX - 0.5 * LT.TH * LT.PX, float(k), 0 if pin == "0" else 1)
    key = lambda x: None if x is None else (x["orient"], x["alt"], x["ns"], x["nr"])
    return dict(f32_same=key(b) == key(b32), N=N, eta=eta, pin=pin, k=k, htxt=htext(k), H=H, L0=L0, aspect=(L0 - LT.TH / 2) / H, b=b,
                arr=LT.fmt_arr(b) if b else "-", nvac=b["nvac"] if b else -1, e=LT.strain(b) if b else math.nan,
                gap=b["s"] / LT.PX if b else math.nan, px_ok=height_px(htext(k)) == k)


def runs(ks):
    out, a = [], ks[0]
    for p, q in zip(ks, ks[1:] + [None]):
        if q != p + 1: out.append((a, p)); a = q
    return out


def fmt_runs(rs):
    return "; ".join(f"{a / 24:.3f}" + (f"–{b / 24:.3f}" if b > a else "") + f" ({a}" + (f"–{b}" if b > a else "") + ")" for a, b in rs)


def main():
    allrows, L = [], []
    rng = {900: "25–36", 1600: "34–48"}
    L += ["# The vacancy table for the Stage 2 registration (decision 57, addendum 1, task 1)", "",
          "Generated by cluster/gen3_stage2_261016/s2_vacancy_table.py (no runs: the replica of the binary's lattice fit). Per cell and pin, "
          "every arrangement the binary's lattice fit chooses with at most 1 vacancy per compartment at a box height H = k/24 sigma within "
          "25–36 sigma (N 900) or 34–48 sigma (N 1600), N and eta kept, L0 = N pi / (8 H eta). The columns from H on are at the height "
          "with the smallest |e| among the heights listed (then the one nearest the stage 1 height, 30 or 40 sigma). Aspect W/H with W = "
          "L0 - 0.025 sigma, the compartment's width; e = h / ((sqrt 3 / 2) d) - 1; gap = the smallest surface gap of the lattice.", "",
          "| N | eta | pin | arrangement (left = right) | vacancies | the heights at which the fit chooses it: H [sigma] (k px) | e over these heights | "
          "H [sigma] (k) | L0 | aspect W/H | e | gap [sigma] |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    bad_px = []
    for N in (900, 1600):
        for eta in ETAS:
            for pin in PINS:
                rows = [fit(N, eta, k, pin) for k in KR[N]]; allrows += rows
                bad_px += [(N, r["k"]) for r in rows if not r["px_ok"]]
                q = [r for r in rows if r["b"] is not None and 0 <= r["nvac"] <= 1 and r["px_ok"]]
                if not q:
                    v = min(r["nvac"] for r in rows if r["b"] is not None)
                    best = min((r for r in rows if r["nvac"] == v), key=lambda r: (abs(r["e"]), abs(r["k"] - KREF[N])))
                    ks = sorted(r["k"] for r in rows if r["nvac"] == v)
                    L.append(f"| {N} | {eta:.2f} | {pin} | NONE in {rng[N]} sigma: the fewest vacancies there are {v} "
                             f"({', '.join(sorted({r['arr'] for r in rows if r['nvac'] == v}))}) | {v} | {fmt_runs(runs(ks))} | - | "
                             f"{best['htxt']} ({best['k']}) | {best['L0']:.6f} | {best['aspect']:.4f} | {100 * best['e']:+.3f} % | {best['gap']:.4f} |")
                    continue
                groups = {}
                for r in q: groups.setdefault((r["arr"], r["nvac"]), []).append(r)
                for (arr, nv), g in sorted(groups.items(), key=lambda it: min(r["k"] for r in it[1])):
                    best = min(g, key=lambda r: (abs(r["e"]), abs(r["k"] - KREF[N])))
                    es = [r["e"] for r in g]
                    L.append(f"| {N} | {eta:.2f} | {pin} | {arr} | {nv} | {fmt_runs(runs(sorted(r['k'] for r in g)))} | "
                             f"{100 * min(es):+.3f} to {100 * max(es):+.3f} % | {best['htxt']} ({best['k']}) | {best['L0']:.6f} | "
                             f"{best['aspect']:.4f} | {100 * best['e']:+.3f} % | {best['gap']:.4f} |")
    s1 = [r for r in allrows if r["k"] == KREF[r["N"]]]
    L += ["", f"- At the stage 1 heights (30 sigma for N 900, 40 sigma for N 1600) the fit chooses at most 1 vacancy in "
              f"{sum(0 <= r['nvac'] <= 1 for r in s1)} of {len(s1)} cases: " +
              "; ".join(f"N {r['N']} eta {r['eta']:.2f} pin {r['pin']}: {r['arr']}, {r['nvac']}" for r in s1) + "."]
    ok = {}
    for r in allrows:
        if r["b"] is not None and 0 <= r["nvac"] <= 1 and r["px_ok"]: ok.setdefault((r["N"], r["eta"], r["pin"]), set()).add(r["k"])
    L += ["- The heights at which both pins have at most 1 vacancy (one box for both pins): " +
          "; ".join(f"N {N} eta {eta:.2f}: {len(b)} of {len(KR[N])}, " + fmt_runs(runs(b))
                    for N in (900, 1600) for eta in ETAS for b in [sorted(ok.get((N, eta, '0'), set()) & ok.get((N, eta, 'turned'), set()))]) + "."]
    L += [f"- Heights checked: {len(allrows)} (cell, pin, k) of 14 cells x 2 pins. Heights whose --height text does not give k px "
          f"through strtof: {len(bad_px)}{' ' + str(sorted(set(bad_px))[:10]) if bad_px else ''}. Heights whose arrangement changes "
          f"when L0 is rounded to float32: {sum(not r['f32_same'] for r in allrows)}."]
    print("\n".join(L))
    with open(MD, "w") as fh: fh.write("\n".join(L) + "\n")
    with open(CSV, "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["N", "eta", "pin", "k_px", "H_text", "L0", "aspect_W_over_H", "arrangement", "vacancies", "e", "gap_sigma", "height_px_ok"])
        for r in allrows:
            w.writerow([r["N"], f"{r['eta']:.2f}", r["pin"], r["k"], r["htxt"], f"{r['L0']:.6f}", f"{r['aspect']:.4f}",
                        r["arr"], r["nvac"], f"{r['e']:.6f}", f"{r['gap']:.6f}", int(r["px_ok"])])
    print(f"\nwritten: {os.path.relpath(MD)}; {os.path.relpath(CSV)} ({len(allrows)} heights)")


if __name__ == "__main__":
    main()
